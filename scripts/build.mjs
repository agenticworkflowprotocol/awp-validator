#!/usr/bin/env node
// Builds the browser bundle (dist/browser/) and the website (dist/site/).
//
// 1. Precompile the vendored JSON Schema with Ajv into a standalone ES module, so that the browser
//    needs neither Ajv's code generation nor `eval`.
// 2. Bundle src/browser.js with esbuild; node:crypto is replaced by src/browser/crypto.js.
// 3. Copy site/ and the bundle into dist/site/ for Cloudflare Pages.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const schema = JSON.parse(readFileSync(join(root, 'vendor/awp-v1alpha1/schema/awp.v1alpha1.json'), 'utf8'));

function precompileSchema() {
  // Same options as src/index.js, plus standalone ES module output.
  const ajv = new Ajv2020({ allErrors: true, strict: true, strictRequired: false, code: { source: true, esm: true } });
  const out = join(root, 'build/schema-validator.mjs');
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `// Generated by scripts/build.mjs from the vendored AWP schema. Do not edit.\n${standaloneCode(ajv, ajv.compile(schema))}`);
}

async function bundle() {
  const banner = `/*! @agenticworkflowprotocol/validator ${pkg.version} | Apache-2.0 | bundles ajv (MIT), yaml (ISC), @noble/hashes (MIT) */`;
  await build({
    entryPoints: [join(root, 'src/browser.js')],
    outfile: join(root, 'dist/browser/awp-validator.mjs'),
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: ['es2022'],
    minify: true,
    sourcemap: true,
    legalComments: 'none',
    banner: { js: banner },
    alias: { 'node:crypto': join(root, 'src/browser/crypto.js') },
    logLevel: 'warning',
  });
}

function site() {
  const out = join(root, 'dist/site');
  rmSync(out, { recursive: true, force: true });
  cpSync(join(root, 'site'), out, { recursive: true });
  cpSync(join(root, 'dist/browser'), join(out, 'lib'), { recursive: true });
  // Spec examples for the example picker, served as static files.
  const examplesDir = join(root, 'vendor/awp-v1alpha1/spec/v1alpha1/examples');
  cpSync(examplesDir, join(out, 'examples'), { recursive: true });
  const { nonManifestExamples = [] } = JSON.parse(readFileSync(join(root, 'vendor/awp-v1alpha1/conformance/index.json'), 'utf8'));
  const examples = readdirSync(examplesDir).filter((f) => /\.(ya?ml|json)$/.test(f) && !nonManifestExamples.includes(f)).sort();
  writeFileSync(join(out, 'examples/index.json'), `${JSON.stringify({ examples }, null, 2)}\n`);
  const html = readFileSync(join(out, 'index.html'), 'utf8')
    .replaceAll('{{version}}', pkg.version)
    .replaceAll('{{specCommit}}', JSON.parse(readFileSync(join(root, 'vendor/awp-v1alpha1/PROVENANCE.json'), 'utf8')).source.commit.slice(0, 7));
  writeFileSync(join(out, 'index.html'), html);
}

rmSync(join(root, 'dist'), { recursive: true, force: true });
precompileSchema();
await bundle();
site();
console.log('built dist/browser/awp-validator.mjs and dist/site/');
